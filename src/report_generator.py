"""
Engineering Report Generator.
Formats complete capstone-grade engineering specification reports
suitable for export, peer review, and field manufacturing execution.
"""

from typing import Dict, Any, List
from datetime import datetime


class EngineeringReportGenerator:
    """Generates publication-ready engineering specification documents."""

    @staticmethod
    def generate_markdown_report(analysis_result: Dict[str, Any], nlp_spec: Dict[str, Any]) -> str:
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        spec = nlp_spec.get("synthesized_engineering_spec", {})
        boundary = nlp_spec.get("boundary_conditions_and_constraints", {})
        ranked = analysis_result.get("ranked_materials", [])
        top_mat = ranked[0] if ranked else None
        leaderboard = analysis_result.get("techno_economic_leaderboard", [])

        report = fr"""# Autonomous Engineering Material Selection & Manufacturing Specification

**Date Generated:** {timestamp}  
**Execution System:** {analysis_result.get('mode_used', 'Engineering Selection System')}  
**Project:** Computational Material Selection & Multi-Objective Ashby Optimization System (EMS-OS)

---

## 1. Engineering Design Specification & Requirements
- **Input Design Specification:** *"{nlp_spec.get('raw_prompt')}"*
- **Component Classification:** `{spec.get('component_classification', 'Mechanical Component')}`
- **Functional Objective:** {spec.get('functional_objective')}
- **Governing Standards Mentioned:** `{spec.get('governing_standards') or 'Standard Engineering Good Practice'}`
- **Submerged Aquatic Exposure:** `{boundary.get('submerged_aquatic_exposure')}`
- **Outdoor Solar UV Exposure:** `{boundary.get('outdoor_uv_exposure')}`
- **Selected Manufacturing Route:** `{boundary.get('manufacturing_process')}`

---

## 2. Mathematical Ashby Optimization Framework
- **Primary Governing Performance Index:** `{spec.get('primary_governing_ashby_index')}` ($M = {spec.get('ashby_mathematical_formula')}$)
- **Physics Derivation Rationale:** {spec.get('ashby_selection_rationale')}

### Top Material Candidates (Ashby Performance Ranking):
| Rank | Material Name | Family | Ashby Metric ($M$) | Density (g/cm³) | $E$ (GPa) | $\sigma_y$ (MPa) | Raw Cost ($/kg) |
| :---: | :--- | :--- | :---: | :---: | :---: | :---: | :---: |
"""
        for i, m in enumerate(ranked[:6], 1):
            report += f"| {i} | {m['name']} | {m['family']} | {m['final_metric']:.2f} | {m['density_g_cm3']:.2f} | {m['youngs_modulus_gpa']:.1f} | {m['yield_strength_mpa']:.1f} | ${m['cost_usd']:.2f} |\n"

        report += fr"""
---

## 3. Synthesized Technical Engineering Recommendation
{analysis_result.get('synthesized_response')}

---

## 4. Empirical Mechanical Properties & Data Provenance
For the top-ranked candidate **{top_mat['name'] if top_mat else 'N/A'}**:
- **Yield Strength ($\sigma_y$):** {top_mat['yield_strength_mpa'] if top_mat else 'N/A'} MPa
- **Density ($\rho$):** {top_mat['density_g_cm3'] if top_mat else 'N/A'} g/cm³
- **Young's Modulus ($E$):** {top_mat['youngs_modulus_gpa'] if top_mat else 'N/A'} GPa
- **Data Source:** Verified Master Engineering Materials Catalog (1,490+ records under ANSI, ISO, DIN, JIS)

---
*Generated by the Engineering Material Selection & Optimization System (EMS-OS).*
"""
        return report
